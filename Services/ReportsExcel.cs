using ClosedXML.Excel;

namespace DTIOneLink.Services
{
    // Builds the server-side Excel export for the Reports page — a real
    // .xlsx workbook (Summary + Report Items), replacing the old client-side
    // CSV (reports.js previously built a Blob in the browser with no
    // formatting at all). Reuses the house style RecordMasterlistExcel.cs
    // established (Calibri, grey bordered header, landscape print).
    public static class ReportsExcel
    {
        public const string ContentType = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";

        public const string OfficeName = "DEPARTMENT OF TRADE AND INDUSTRY - LAGUNA PROVINCIAL OFFICE";

        public sealed record Row(
            string Id, string Category, string Title, string Owner,
            string Details, string? Flag, DateTime LastActivityUtc);

        public sealed record Sheet(
            DateTime GeneratedAtUtc, string GeneratedBy, string Scope,
            string PeriodLabel, string? CategoryFilter, string? SearchTerm,
            IReadOnlyList<Row> Rows);

        private static readonly string[] Headers =
        {
            "No.", "Category", "ID", "Title", "Owner", "Status / Details", "Flag", "Last Activity"
        };

        private static readonly double[] Widths = { 5, 15, 12, 42, 20, 34, 14, 20 };
        private static readonly XLAlignmentHorizontalValues[] Align =
        {
            XLAlignmentHorizontalValues.Center, XLAlignmentHorizontalValues.Left,
            XLAlignmentHorizontalValues.Left, XLAlignmentHorizontalValues.Left,
            XLAlignmentHorizontalValues.Left, XLAlignmentHorizontalValues.Left,
            XLAlignmentHorizontalValues.Center, XLAlignmentHorizontalValues.Center
        };

        // Fixed category order, same as reports.js's GROUPS — not just
        // whatever order rows happen to appear in.
        private static readonly string[] CategoryOrder =
        {
            "Active Tasks", "Completed Tasks", "Task History", "Retained", "Archived", "Disposed"
        };

        private const double DataFontSize = 10;

        public static byte[] Build(Sheet sheet)
        {
            using var workbook = new XLWorkbook();
            BuildSummarySheet(workbook, sheet);
            BuildDetailSheet(workbook, sheet);

            using var stream = new MemoryStream();
            workbook.SaveAs(stream);
            return stream.ToArray();
        }

        private static void BuildSummarySheet(XLWorkbook workbook, Sheet sheet)
        {
            var ws = workbook.Worksheets.Add("Summary");
            ws.Style.Font.FontName = "Calibri";
            ws.Style.Font.FontSize = 11;
            ws.Column(1).Width = 26;
            ws.Column(2).Width = 48;

            ws.Cell("A1").Value = OfficeName;
            ws.Cell("A1").Style.Font.Bold = true;
            ws.Cell("A1").Style.Font.FontSize = 12;
            ws.Cell("A2").Value = "DTI OneLink";
            ws.Cell("A3").Value = "Reports Export";
            ws.Cell("A3").Style.Font.Bold = true;
            ws.Cell("A3").Style.Font.FontSize = 16;
            ws.Row(3).Height = 24;

            var r = 5;
            void MetaRow(string label, string value)
            {
                ws.Cell(r, 1).Value = label;
                ws.Cell(r, 1).Style.Font.Bold = true;
                ws.Cell(r, 2).Value = value;
                r++;
            }

            MetaRow("Reporting Period:", sheet.PeriodLabel);
            MetaRow("Category Filter:", string.IsNullOrWhiteSpace(sheet.CategoryFilter) || sheet.CategoryFilter == "All Categories"
                ? "All Categories" : sheet.CategoryFilter);
            if (!string.IsNullOrWhiteSpace(sheet.SearchTerm))
            {
                MetaRow("Search Filter:", sheet.SearchTerm);
            }
            MetaRow("Scope:", sheet.Scope);
            MetaRow("Generated By:", sheet.GeneratedBy);
            MetaRow("Generated At:", TimeZoneHelper.ToPhilippineTime(sheet.GeneratedAtUtc).ToString("MMMM d, yyyy h:mm tt") + " (Philippine Time)");
            r++;

            // ── Counts, matching the exported dataset exactly — never a
            // different/office-wide total, per the no-mismatched-summaries rule. ──
            ws.Cell(r, 1).Value = "Counts in This Export";
            ws.Cell(r, 1).Style.Font.Bold = true;
            ws.Cell(r, 1).Style.Font.FontSize = 13;
            r++;
            var tableTop = r;
            ws.Cell(r, 1).Value = "Category";
            ws.Cell(r, 2).Value = "Count";
            var header = ws.Range(r, 1, r, 2);
            header.Style.Font.Bold = true;
            header.Style.Fill.BackgroundColor = XLColor.FromHtml("#BFBFBF");
            r++;

            var counts = sheet.Rows.GroupBy(x => x.Category).ToDictionary(g => g.Key, g => g.Count());
            foreach (var category in CategoryOrder)
            {
                if (!counts.TryGetValue(category, out var count)) continue;
                ws.Cell(r, 1).Value = category;
                ws.Cell(r, 2).Value = count;
                ws.Cell(r, 2).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                r++;
            }
            // Any category not in the fixed order (shouldn't normally happen,
            // but don't silently drop a count if one ever appears).
            foreach (var kv in counts.Where(kv => !CategoryOrder.Contains(kv.Key)))
            {
                ws.Cell(r, 1).Value = kv.Key;
                ws.Cell(r, 2).Value = kv.Value;
                r++;
            }

            ws.Cell(r, 1).Value = "Total";
            ws.Cell(r, 1).Style.Font.Bold = true;
            ws.Cell(r, 2).Value = sheet.Rows.Count;
            ws.Cell(r, 2).Style.Font.Bold = true;
            var totalRow = ws.Range(r, 1, r, 2);
            totalRow.Style.Border.TopBorder = XLBorderStyleValues.Thin;
            r++;

            var countsTable = ws.Range(tableTop, 1, r - 1, 2);
            countsTable.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
            countsTable.Style.Border.InsideBorder = XLBorderStyleValues.Thin;

            ws.PageSetup.PageOrientation = XLPageOrientation.Portrait;
            ws.PageSetup.PaperSize = XLPaperSize.A4Paper;
            ws.PageSetup.FitToPages(1, 1);
            ws.PageSetup.Margins.Left = 0.5; ws.PageSetup.Margins.Right = 0.5;
            ws.PageSetup.Margins.Top = 0.6; ws.PageSetup.Margins.Bottom = 0.6;
            ws.PageSetup.PrintAreas.Add(1, 1, r, 2);
        }

        private static void BuildDetailSheet(XLWorkbook workbook, Sheet sheet)
        {
            var ws = workbook.Worksheets.Add("Report Items");
            ws.Style.Font.FontName = "Calibri";
            ws.Style.Font.FontSize = 11;

            for (var c = 0; c < Widths.Length; c++)
            {
                ws.Column(c + 1).Width = Widths[c];
            }

            const int headerRow = 1;
            for (var c = 0; c < Headers.Length; c++)
            {
                ws.Cell(headerRow, c + 1).Value = Headers[c];
            }
            var header = ws.Range(headerRow, 1, headerRow, Headers.Length);
            header.Style.Fill.BackgroundColor = XLColor.FromHtml("#BFBFBF");
            header.Style.Font.Bold = true;
            header.Style.Font.FontSize = DataFontSize;
            header.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
            header.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
            header.Style.Alignment.WrapText = true;
            ws.Row(headerRow).Height = 20;

            var r = headerRow + 1;
            var no = 1;
            foreach (var row in sheet.Rows)
            {
                ws.Cell(r, 1).Value = no++;
                ws.Cell(r, 2).Value = row.Category;
                // A task's ID is always system-built ("TASK-0001"/"LOG-123"),
                // but a record's ID is its user-typed Code field — same
                // formula-injection guard as Title/Owner/Details below.
                ws.Cell(r, 3).SetValue(SafeText(row.Id));
                ws.Cell(r, 4).SetValue(SafeText(row.Title));
                ws.Cell(r, 5).SetValue(SafeText(row.Owner));
                ws.Cell(r, 6).SetValue(SafeText(row.Details));
                ws.Cell(r, 7).Value = row.Flag ?? "";
                // A real Excel date/time value (Philippine local), not the
                // page's relative "3 days ago" text — sortable/filterable.
                var localCell = ws.Cell(r, 8);
                localCell.Value = TimeZoneHelper.ToPhilippineTime(row.LastActivityUtc);
                localCell.Style.DateFormat.Format = "dd-mmm-yyyy h:mm AM/PM";

                for (var c = 0; c < Align.Length; c++)
                {
                    ws.Cell(r, c + 1).Style.Alignment.Horizontal = Align[c];
                }
                r++;
            }
            var lastRow = Math.Max(headerRow, r - 1);

            var body = ws.Range(headerRow + 1, 1, lastRow, Headers.Length);
            body.Style.Font.FontSize = DataFontSize;
            body.Style.Alignment.Vertical = XLAlignmentVerticalValues.Center;
            body.Style.Alignment.WrapText = true;

            var table = ws.Range(headerRow, 1, lastRow, Headers.Length);
            table.Style.Border.InsideBorder = XLBorderStyleValues.Thin;
            table.Style.Border.OutsideBorder = XLBorderStyleValues.Medium;

            if (lastRow > headerRow)
            {
                ws.Range(headerRow, 1, lastRow, Headers.Length).SetAutoFilter();
            }
            ws.SheetView.FreezeRows(headerRow);

            ws.PageSetup.PageOrientation = XLPageOrientation.Landscape;
            ws.PageSetup.PaperSize = XLPaperSize.A4Paper;
            ws.PageSetup.FitToPages(1, 0);
            ws.PageSetup.Margins.Left = 0.4; ws.PageSetup.Margins.Right = 0.4;
            ws.PageSetup.Margins.Top = 0.5; ws.PageSetup.Margins.Bottom = 0.5;
            ws.PageSetup.SetRowsToRepeatAtTop(headerRow, headerRow);
            ws.PageSetup.PrintAreas.Add(1, 1, lastRow, Headers.Length);
        }

        // Excel formula injection guard: a value beginning with =, +, -, or @
        // can be interpreted as a formula by some spreadsheet applications
        // (notably when the data later round-trips through CSV). Task
        // titles/record titles/user names are free text an employee typed,
        // so neutralize a leading trigger character by forcing it visibly
        // literal rather than silently stripping it.
        private static string SafeText(string? value)
        {
            var s = value ?? "";
            return s.Length > 0 && (s[0] is '=' or '+' or '-' or '@') ? "'" + s : s;
        }
    }
}
